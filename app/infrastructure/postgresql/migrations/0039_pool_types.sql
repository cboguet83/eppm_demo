CREATE FUNCTION eppm.guard_pool_type_parent_cycle() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, eppm AS $$
BEGIN
    IF NEW.parent_pool_type_id IS NULL THEN RETURN NEW; END IF;
    -- Shared catalog writes are SERIALIZABLE, so conflicting snapshots are replayed.
    PERFORM pg_advisory_xact_lock(hashtextextended('eppm:pool-type-hierarchy', 0));
    IF EXISTS (
        WITH RECURSIVE ancestors(id) AS (
            SELECT NEW.parent_pool_type_id
            UNION
            SELECT p.parent_pool_type_id FROM eppm.pool_type p
            JOIN ancestors a ON p.id=a.id WHERE p.parent_pool_type_id IS NOT NULL
        ) SELECT 1 FROM ancestors WHERE id=NEW.id
    ) THEN
        RAISE EXCEPTION 'Pool type parent link would create a cycle' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION eppm.guard_pool_type_parent_cycle() FROM PUBLIC;
CREATE TRIGGER pool_type_no_cycle BEFORE INSERT OR UPDATE OF parent_pool_type_id
    ON eppm.pool_type FOR EACH ROW EXECUTE FUNCTION eppm.guard_pool_type_parent_cycle();

DO $$
DECLARE target text;
BEGIN
    FOREACH target IN ARRAY ARRAY['pool_type','pool_type_translation'] LOOP
