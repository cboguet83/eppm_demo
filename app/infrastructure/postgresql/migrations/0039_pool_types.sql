-- Required resource-pool classifications, independent of hierarchy classifications.
CREATE TABLE eppm.pool_type (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (name = btrim(name) AND length(name) BETWEEN 1 AND 120),
    parent_pool_type_id bigint REFERENCES eppm.pool_type(id) ON DELETE RESTRICT,
    CONSTRAINT pool_type_not_self CHECK (parent_pool_type_id IS DISTINCT FROM id)
);
CREATE UNIQUE INDEX pool_type_name_unique ON eppm.pool_type(lower(name));
CREATE INDEX pool_type_parent ON eppm.pool_type(parent_pool_type_id);
CREATE TABLE eppm.pool_type_translation (
    pool_type_id bigint NOT NULL REFERENCES eppm.pool_type(id) ON DELETE CASCADE,
    locale text NOT NULL CHECK (locale IN ('en','fr','de','lb','pt')),
    name text NOT NULL CHECK (name = btrim(name) AND length(name) BETWEEN 1 AND 120),
    PRIMARY KEY(pool_type_id,locale)
);
