        EXECUTE format('CREATE POLICY business_insert ON eppm.%I FOR INSERT TO eppm_runtime
            WITH CHECK ((SELECT eppm.has_global_permission(''business.manage'')))',target);
        EXECUTE format('CREATE POLICY business_update ON eppm.%I FOR UPDATE TO eppm_runtime
            USING ((SELECT eppm.has_global_permission(''business.manage'')))
            WITH CHECK ((SELECT eppm.has_global_permission(''business.manage'')))',target);
        EXECUTE format('CREATE POLICY business_delete ON eppm.%I FOR DELETE TO eppm_runtime
            USING ((SELECT eppm.has_global_permission(''business.manage'')))',target);
        EXECUTE format('CREATE TRIGGER authorize_business BEFORE INSERT OR UPDATE OR DELETE ON eppm.%I
            FOR EACH ROW EXECUTE FUNCTION eppm.guard_business_write(''shared'')',target);
        EXECUTE format('GRANT SELECT,INSERT,UPDATE,DELETE ON eppm.%I TO eppm_runtime',target);
    END LOOP;
END $$;
