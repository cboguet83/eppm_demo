-- Historical conversion is calculated and validated by Python, never by a SQL function.
CREATE TABLE eppm.project_financial_transaction (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES eppm.project(id) ON DELETE CASCADE,
    fiscal_year integer NOT NULL CHECK (fiscal_year BETWEEN 1 AND 9999),
    amount numeric(19,2) NOT NULL CHECK (amount BETWEEN -92233720368547758.07 AND 92233720368547758.07),
    currency text NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    exchange_rate numeric(28,10) NOT NULL CHECK (exchange_rate > 0 AND exchange_rate < 'Infinity'::numeric),
    amount_base_currency numeric(19,2) NOT NULL CHECK (amount_base_currency BETWEEN -92233720368547758.07 AND 92233720368547758.07),
    financial_record_type text NOT NULL CHECK (financial_record_type IN ('COMMITMENT','ACTUAL')),
    spending_type text NOT NULL,
    wbs text NOT NULL CHECK (length(trim(wbs)) > 0),
    accounting_date date,
    description text,
    counterparty text,
    invoice_number text,
    order_position_number text,
    order_number text,
    source_transaction_id bigint REFERENCES eppm.project_financial_transaction(id) ON DELETE RESTRICT
);
CREATE INDEX project_financial_transaction_year ON eppm.project_financial_transaction(project_id,fiscal_year,id);
CREATE INDEX project_financial_transaction_source ON eppm.project_financial_transaction(source_transaction_id);

ALTER TABLE eppm.project_financial_transaction ENABLE ROW LEVEL SECURITY;
ALTER TABLE eppm.project_financial_transaction FORCE ROW LEVEL SECURITY;
CREATE POLICY transaction_read ON eppm.project_financial_transaction FOR SELECT TO eppm_runtime
    USING (project_id IN (SELECT unnest(eppm.permission_projects('project.read'))));
CREATE POLICY transaction_insert ON eppm.project_financial_transaction FOR INSERT TO eppm_runtime
    WITH CHECK (project_id IN (SELECT unnest(eppm.permission_projects('project.read')))
        AND ((SELECT eppm.has_global_permission('finance.edit'))
             OR (financial_record_type IN ('COMMITMENT','ACTUAL')
                 AND project_id IN (SELECT unnest(eppm.permission_projects('project.edit'))))));
CREATE POLICY transaction_update ON eppm.project_financial_transaction FOR UPDATE TO eppm_runtime
    USING (project_id IN (SELECT unnest(eppm.permission_projects('project.read')))
        AND ((SELECT eppm.has_global_permission('finance.edit'))
             OR (financial_record_type IN ('COMMITMENT','ACTUAL')
                 AND project_id IN (SELECT unnest(eppm.permission_projects('project.edit'))))))
    WITH CHECK (project_id IN (SELECT unnest(eppm.permission_projects('project.read')))
        AND ((SELECT eppm.has_global_permission('finance.edit'))
             OR (financial_record_type IN ('COMMITMENT','ACTUAL')
                 AND project_id IN (SELECT unnest(eppm.permission_projects('project.edit'))))));
CREATE POLICY transaction_delete ON eppm.project_financial_transaction FOR DELETE TO eppm_runtime
    USING (project_id IN (SELECT unnest(eppm.permission_projects('project.read')))
        AND ((SELECT eppm.has_global_permission('finance.edit'))
             OR (financial_record_type IN ('COMMITMENT','ACTUAL')
                 AND project_id IN (SELECT unnest(eppm.permission_projects('project.edit'))))));
GRANT SELECT,INSERT,DELETE ON eppm.project_financial_transaction TO eppm_runtime;
-- A correction cannot move a record to another project or turn a commitment into an actual.
GRANT UPDATE(fiscal_year,amount,currency,exchange_rate,amount_base_currency,spending_type,wbs,
    accounting_date,description,counterparty,invoice_number,order_position_number,order_number,source_transaction_id)
    ON eppm.project_financial_transaction TO eppm_runtime;
GRANT USAGE ON SEQUENCE eppm.project_financial_transaction_id_seq TO eppm_runtime;
