CREATE TABLE eppm.finance_snapshot (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number bigint NOT NULL UNIQUE CHECK (number > 0),
    name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 120),
    status text NOT NULL CHECK (status IN ('Draft', 'Proposed', 'Approved', 'Canceled')),
    author text NOT NULL, created_at bigint NOT NULL,
    base_id bigint REFERENCES eppm.finance_snapshot(id) ON DELETE RESTRICT,
    sealed boolean NOT NULL DEFAULT false
);
CREATE TABLE eppm.finance_row (
    snapshot_id bigint NOT NULL REFERENCES eppm.finance_snapshot(id) ON DELETE RESTRICT,
    code text NOT NULL CHECK (code ~ '^#?[A-Za-z0-9._-]{1,128}$'),
    position integer NOT NULL CHECK (position >= 0),
    PRIMARY KEY (snapshot_id, code), UNIQUE (snapshot_id, position)
);
CREATE TABLE eppm.finance_amount (
    snapshot_id bigint NOT NULL, code text NOT NULL,
    year integer NOT NULL CHECK (year BETWEEN 1 AND 9999),
    amount numeric NOT NULL CHECK (amount >= 0 AND amount < 'Infinity'::numeric AND amount * 100 = trunc(amount * 100)),
    PRIMARY KEY (snapshot_id, code, year),
    FOREIGN KEY (snapshot_id, code) REFERENCES eppm.finance_row(snapshot_id, code) ON DELETE RESTRICT
);
CREATE TABLE eppm.finance_cancellation (
    snapshot_id bigint PRIMARY KEY REFERENCES eppm.finance_snapshot(id) ON DELETE RESTRICT,
    previous_status text NOT NULL CHECK (previous_status IN ('Draft', 'Proposed', 'Approved')),
    author text NOT NULL, occurred_at bigint NOT NULL
);

