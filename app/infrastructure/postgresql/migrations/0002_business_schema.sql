CREATE INDEX pool_assignment_pool ON eppm.resource_pool_assignment(pool_id);
CREATE INDEX pool_assignment_project ON eppm.resource_pool_assignment(project_id);
CREATE INDEX pool_assignment_task ON eppm.resource_pool_assignment(task_id);
