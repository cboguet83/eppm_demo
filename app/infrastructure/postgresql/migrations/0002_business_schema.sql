CREATE TABLE eppm.resource_pool (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE, description text DEFAULT '',
    capacity_fte double precision CHECK (capacity_fte >= 0 AND capacity_fte < 'Infinity'::double precision),
    created_at timestamptz DEFAULT current_timestamp,
    hierarchy_type_id bigint REFERENCES eppm.hierarchy_type(id) ON DELETE RESTRICT
);
CREATE INDEX resource_pool_hierarchy_type ON eppm.resource_pool(hierarchy_type_id);
CREATE TABLE eppm.resource_pool_group (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE, description text DEFAULT '',
    created_at timestamptz DEFAULT current_timestamp,
    hierarchy_type_id bigint REFERENCES eppm.hierarchy_type(id) ON DELETE RESTRICT
);
CREATE INDEX resource_pool_group_hierarchy_type ON eppm.resource_pool_group(hierarchy_type_id);
CREATE TABLE eppm.resource_pool_group_member (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id bigint NOT NULL REFERENCES eppm.resource_pool_group(id) ON DELETE CASCADE,
    pool_id bigint REFERENCES eppm.resource_pool(id) ON DELETE CASCADE,
    child_group_id bigint REFERENCES eppm.resource_pool_group(id) ON DELETE CASCADE,
    CHECK ((pool_id IS NOT NULL) <> (child_group_id IS NOT NULL)),
    CHECK (child_group_id IS NULL OR group_id <> child_group_id),
    UNIQUE (group_id, pool_id), UNIQUE (group_id, child_group_id)
);
CREATE TABLE eppm.resource_pool_mapping (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pool_id bigint NOT NULL REFERENCES eppm.resource_pool(id) ON DELETE CASCADE,
    target_type text NOT NULL CHECK (target_type IN ('team', 'employee', 'function')),
    target_id bigint NOT NULL,
    allocation_pct double precision NOT NULL DEFAULT 100 CHECK (allocation_pct BETWEEN 0 AND 100),
    UNIQUE (pool_id, target_type, target_id)
);
CREATE INDEX pool_mapping_target ON eppm.resource_pool_mapping(target_type, target_id);
CREATE TABLE eppm.resource_pool_assignment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pool_id bigint NOT NULL REFERENCES eppm.resource_pool(id) ON DELETE CASCADE,
    project_id bigint NOT NULL REFERENCES eppm.project(id) ON DELETE CASCADE,
