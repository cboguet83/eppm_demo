-- Native baseline of the accepted application. No SQLite business data is imported.
-- Runtime table privileges are granted with permanent security policies later.
SET LOCAL search_path = pg_catalog, eppm;

CREATE TABLE eppm.hierarchy_type (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE CHECK (code ~ '^[a-z][a-z0-9_]{0,63}$')
);
CREATE TABLE eppm.hierarchy_type_translation (
    hierarchy_type_id bigint NOT NULL REFERENCES eppm.hierarchy_type(id) ON DELETE CASCADE,
    locale text NOT NULL CHECK (locale IN ('en', 'fr', 'de', 'lb', 'pt')),
    label text NOT NULL CHECK (length(trim(label)) BETWEEN 1 AND 120),
    PRIMARY KEY (hierarchy_type_id, locale)
);
CREATE TABLE eppm.schema_groups (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_name text NOT NULL UNIQUE,
    display_order integer NOT NULL UNIQUE
);
CREATE TABLE eppm.schema_parameters (
    param_id text PRIMARY KEY,
    group_id bigint REFERENCES eppm.schema_groups(id) ON DELETE RESTRICT,
    param_name text NOT NULL,
    param_type text NOT NULL,
    mandatory boolean DEFAULT false,
    alias text DEFAULT '',
    applies_to_all boolean NOT NULL DEFAULT true
);
CREATE TABLE eppm.schema_parameter_translation (
    param_id text NOT NULL REFERENCES eppm.schema_parameters(param_id) ON DELETE CASCADE,
    locale text NOT NULL CHECK (length(trim(locale)) > 0),
    alias text NOT NULL CHECK (length(trim(alias)) > 0),
    PRIMARY KEY (param_id, locale)
);
CREATE TABLE eppm.schema_param_options (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    param_id text NOT NULL REFERENCES eppm.schema_parameters(param_id) ON DELETE RESTRICT,
    option_value text NOT NULL,
    display_order integer DEFAULT 0
);
CREATE INDEX schema_option_parameter ON eppm.schema_param_options(param_id, display_order, id);
CREATE TABLE eppm.project_type (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (length(trim(name)) > 0),
    description text NOT NULL DEFAULT '',
    is_general boolean NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX project_type_name ON eppm.project_type(lower(name));
CREATE UNIQUE INDEX one_general_project_type ON eppm.project_type(is_general) WHERE is_general;
CREATE TABLE eppm.project_type_property (
    project_type_id bigint NOT NULL REFERENCES eppm.project_type(id) ON DELETE CASCADE,
    param_id text NOT NULL REFERENCES eppm.schema_parameters(param_id) ON DELETE CASCADE,
    PRIMARY KEY (project_type_id, param_id)
);
CREATE TABLE eppm.project_type_property_rule (
    project_type_id bigint NOT NULL REFERENCES eppm.project_type(id) ON DELETE CASCADE,
    param_id text NOT NULL REFERENCES eppm.schema_parameters(param_id) ON DELETE CASCADE,
    mandatory_override boolean,
    PRIMARY KEY (project_type_id, param_id)
);
CREATE TABLE eppm.project_type_property_default (
    project_type_id bigint NOT NULL REFERENCES eppm.project_type(id) ON DELETE CASCADE,
    param_id text NOT NULL REFERENCES eppm.schema_parameters(param_id) ON DELETE RESTRICT,
    kind text NOT NULL CHECK (kind IN ('null', 'empty', 'text', 'number', 'date', 'list')),
    text_value text, number_value numeric, date_value date,
    CHECK ((kind = 'text' AND text_value IS NOT NULL AND number_value IS NULL AND date_value IS NULL)
        OR (kind = 'number' AND number_value IS NOT NULL AND text_value IS NULL AND date_value IS NULL)
        OR (kind = 'date' AND date_value IS NOT NULL AND text_value IS NULL AND number_value IS NULL)
        OR (kind IN ('null', 'empty', 'list') AND text_value IS NULL AND number_value IS NULL AND date_value IS NULL)),
    PRIMARY KEY (project_type_id, param_id)
);
CREATE INDEX project_type_default_parameter ON eppm.project_type_property_default(param_id);
CREATE TABLE eppm.project_type_property_default_item (
    project_type_id bigint NOT NULL, param_id text NOT NULL,
    position integer NOT NULL CHECK (position >= 0), value text NOT NULL,
    PRIMARY KEY (project_type_id, param_id, position),
    UNIQUE (project_type_id, param_id, value),
    FOREIGN KEY (project_type_id, param_id)
        REFERENCES eppm.project_type_property_default(project_type_id, param_id) ON DELETE CASCADE
);

