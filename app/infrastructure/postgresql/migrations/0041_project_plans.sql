-- Plan contents are append-only. Lifecycle validation is implemented in Python.
CREATE TABLE eppm.plan_status (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE
);
CREATE TABLE eppm.plan_status_translation (
    status_id bigint NOT NULL REFERENCES eppm.plan_status(id),
    locale text NOT NULL,
    label text NOT NULL,
    PRIMARY KEY(status_id,locale)
);
