-- Projection writes are authorized by Python plan adoption. RLS independently
-- limits writes to the actor's editable/approvable projects; no lifecycle trigger.
DROP TRIGGER authorize_business ON eppm.project_task;
DROP TRIGGER authorize_business ON eppm.task_dependencies;
DROP TRIGGER authorize_business ON eppm.task_tag;
DROP TRIGGER authorize_business ON eppm.resource_pool_assignment;
DROP TRIGGER authorize_business ON eppm.project_dependency;
DO $$
DECLARE target text; owner_expression text; allowed text;
BEGIN
    FOREACH target IN ARRAY ARRAY['project_task','task_dependencies','task_tag','resource_pool_assignment','project_dependency'] LOOP
        owner_expression := CASE WHEN target IN ('task_dependencies','task_tag')
            THEN '(SELECT project_id FROM eppm.project_task WHERE id=task_id)' ELSE 'project_id' END;
        allowed := owner_expression || ' IN (SELECT unnest(eppm.permission_projects(''project.edit''))) OR '
            || owner_expression || ' IN (SELECT unnest(eppm.permission_projects(''project.approve'')))';
        EXECUTE format('DROP POLICY IF EXISTS business_insert ON eppm.%I',target);
        EXECUTE format('DROP POLICY IF EXISTS business_update ON eppm.%I',target);
        EXECUTE format('DROP POLICY IF EXISTS business_delete ON eppm.%I',target);
        EXECUTE format('CREATE POLICY plan_projection_insert ON eppm.%I FOR INSERT TO eppm_runtime WITH CHECK(%s)',target,allowed);
        EXECUTE format('CREATE POLICY plan_projection_update ON eppm.%I FOR UPDATE TO eppm_runtime USING(%s) WITH CHECK(%s)',target,allowed,allowed);
        EXECUTE format('CREATE POLICY plan_projection_delete ON eppm.%I FOR DELETE TO eppm_runtime USING(%s)',target,allowed);
    END LOOP;
END $$;
