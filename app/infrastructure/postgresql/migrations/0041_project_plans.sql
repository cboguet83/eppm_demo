CREATE TABLE eppm.project_plan (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES eppm.project(id) ON DELETE CASCADE,
    version integer NOT NULL CHECK(version>0),
    name text NOT NULL CHECK(length(trim(name))>0),
    status_id bigint NOT NULL DEFAULT 2 REFERENCES eppm.plan_status(id),
    source_plan_id bigint REFERENCES eppm.project_plan(id),
    is_current boolean NOT NULL DEFAULT false,
    is_baseline boolean NOT NULL DEFAULT false,
    revision bigint NOT NULL DEFAULT 1,
    author text NOT NULL,
    created_at timestamptz NOT NULL,
    content jsonb NOT NULL,
    UNIQUE(project_id,version)
);
CREATE UNIQUE INDEX one_current_project_plan ON eppm.project_plan(project_id) WHERE is_current;
CREATE UNIQUE INDEX one_baseline_project_plan ON eppm.project_plan(project_id) WHERE is_baseline;
CREATE TABLE eppm.project_plan_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES eppm.project(id) ON DELETE CASCADE,
    plan_id bigint NOT NULL REFERENCES eppm.project_plan(id),
    action text NOT NULL,
    old_value text,
    new_value text,
    author text NOT NULL,
    created_at timestamptz NOT NULL
);
ALTER TABLE eppm.project_plan ENABLE ROW LEVEL SECURITY;
ALTER TABLE eppm.project_plan_event ENABLE ROW LEVEL SECURITY;
CREATE POLICY plan_read ON eppm.project_plan FOR SELECT TO eppm_runtime
    USING(project_id IN (SELECT unnest(eppm.permission_projects('project.read'))));
CREATE POLICY plan_insert ON eppm.project_plan FOR INSERT TO eppm_runtime
    WITH CHECK(project_id IN (SELECT unnest(eppm.permission_projects('project.edit'))));
CREATE POLICY plan_metadata ON eppm.project_plan FOR UPDATE TO eppm_runtime
    USING(project_id IN (SELECT unnest(eppm.permission_projects('project.edit')))
       OR project_id IN (SELECT unnest(eppm.permission_projects('project.approve'))))
    WITH CHECK(project_id IN (SELECT unnest(eppm.permission_projects('project.edit')))
       OR project_id IN (SELECT unnest(eppm.permission_projects('project.approve'))));
CREATE POLICY plan_event_read ON eppm.project_plan_event FOR SELECT TO eppm_runtime
    USING(project_id IN (SELECT unnest(eppm.permission_projects('project.read'))));
CREATE POLICY plan_event_insert ON eppm.project_plan_event FOR INSERT TO eppm_runtime
    WITH CHECK(project_id IN (SELECT unnest(eppm.permission_projects('project.edit')))
       OR project_id IN (SELECT unnest(eppm.permission_projects('project.approve'))));
GRANT SELECT ON eppm.plan_status,eppm.plan_status_translation,eppm.project_plan,eppm.project_plan_event TO eppm_runtime;
