-- Strategic priority is a native, optional project classification.
CREATE TABLE eppm.strategic_priority (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    display_order integer NOT NULL UNIQUE
);
CREATE TABLE eppm.strategic_priority_translation (
    strategic_priority_id bigint NOT NULL REFERENCES eppm.strategic_priority(id) ON DELETE CASCADE,
    locale text NOT NULL,
    label text NOT NULL,
    PRIMARY KEY (strategic_priority_id, locale)
);
INSERT INTO eppm.strategic_priority(code,display_order) VALUES
    ('strategic',1),('high',2),('medium',3),('low',4);
INSERT INTO eppm.strategic_priority_translation(strategic_priority_id,locale,label)
    SELECT id,'en',initcap(code) FROM eppm.strategic_priority;
ALTER TABLE eppm.project ADD COLUMN strategic_priority_id bigint
    REFERENCES eppm.strategic_priority(id) ON DELETE RESTRICT;
CREATE INDEX project_strategic_priority ON eppm.project(strategic_priority_id);
ALTER TABLE eppm.strategic_priority ENABLE ROW LEVEL SECURITY;
ALTER TABLE eppm.strategic_priority FORCE ROW LEVEL SECURITY;
ALTER TABLE eppm.strategic_priority_translation ENABLE ROW LEVEL SECURITY;
ALTER TABLE eppm.strategic_priority_translation FORCE ROW LEVEL SECURITY;
CREATE POLICY shared_read ON eppm.strategic_priority TO eppm_runtime
    USING ((SELECT eppm.has_business_read()));
CREATE POLICY shared_read ON eppm.strategic_priority_translation TO eppm_runtime
    USING ((SELECT eppm.has_business_read()));
GRANT SELECT ON eppm.strategic_priority,eppm.strategic_priority_translation TO eppm_runtime;
