-- Absolute reductions apply inclusively and add when periods overlap.
CREATE TABLE eppm.resource_pool_capacity_exception (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pool_id bigint NOT NULL REFERENCES eppm.resource_pool(id) ON DELETE CASCADE,
    start_date date NOT NULL,
    end_date date NOT NULL,
    reduction_fte numeric(12,3) NOT NULL CHECK (reduction_fte > 0 AND reduction_fte < 'Infinity'::numeric),
    reason text NOT NULL DEFAULT '',
    CHECK (end_date >= start_date AND end_date-start_date < 9125)
);
CREATE INDEX pool_exception_owner ON eppm.resource_pool_capacity_exception(pool_id,start_date,end_date);
ALTER TABLE eppm.resource_pool_capacity_exception ENABLE ROW LEVEL SECURITY;
ALTER TABLE eppm.resource_pool_capacity_exception FORCE ROW LEVEL SECURITY;
CREATE POLICY business_select ON eppm.resource_pool_capacity_exception FOR SELECT TO eppm_runtime USING ((SELECT eppm.has_business_read()));
CREATE POLICY business_insert ON eppm.resource_pool_capacity_exception FOR INSERT TO eppm_runtime WITH CHECK ((SELECT eppm.has_global_permission('business.manage')));
CREATE POLICY business_update ON eppm.resource_pool_capacity_exception FOR UPDATE TO eppm_runtime USING ((SELECT eppm.has_global_permission('business.manage'))) WITH CHECK ((SELECT eppm.has_global_permission('business.manage')));
CREATE POLICY business_delete ON eppm.resource_pool_capacity_exception FOR DELETE TO eppm_runtime USING ((SELECT eppm.has_global_permission('business.manage')));
CREATE TRIGGER authorize_business BEFORE INSERT OR UPDATE OR DELETE ON eppm.resource_pool_capacity_exception
FOR EACH ROW EXECUTE FUNCTION eppm.guard_business_write('shared');
CREATE TRIGGER invalidate_capacity AFTER INSERT OR UPDATE OR DELETE ON eppm.resource_pool_capacity_exception
FOR EACH ROW EXECUTE FUNCTION eppm.invalidate_business_caches('pool');
GRANT SELECT,INSERT,UPDATE,DELETE ON eppm.resource_pool_capacity_exception TO eppm_runtime;
GRANT USAGE ON SEQUENCE eppm.resource_pool_capacity_exception_id_seq TO eppm_runtime;

CREATE FUNCTION eppm.pool_effective_capacity(requested bigint[])
RETURNS TABLE(pool_id bigint,base double precision,calendar jsonb)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,eppm,pg_temp AS $$
    WITH staffing AS MATERIALIZED (
        SELECT p.id AS pool_id,
            CASE WHEN s.has_assigned_resources THEN s.assigned_capacity_fte
                 ELSE coalesce(eppm.capacity_round3(p.capacity_fte),s.assigned_capacity_fte) END AS base,
            CASE WHEN s.has_assigned_resources THEN s.daily_assigned_capacity ELSE '{}'::jsonb END AS calendar
        FROM eppm.pool_staffing(requested) s JOIN eppm.resource_pool p ON p.id=s.pool_id
    ), reductions AS (
        SELECT x.pool_id,x.start_date+n AS day,sum(x.reduction_fte)::double precision AS reduction
        FROM eppm.resource_pool_capacity_exception x CROSS JOIN LATERAL generate_series(0,x.end_date-x.start_date) n
        WHERE x.pool_id=ANY(requested) GROUP BY x.pool_id,x.start_date+n
    ), days AS (
        SELECT s.pool_id,j.key::date AS day FROM staffing s CROSS JOIN LATERAL jsonb_each(s.calendar) j
        UNION SELECT r.pool_id,r.day FROM reductions r
    ) SELECT s.pool_id,s.base,coalesce((SELECT jsonb_object_agg(to_char(d.day,'YYYY-MM-DD'),
        eppm.capacity_round3(greatest(0.0,coalesce((s.calendar->>to_char(d.day,'YYYY-MM-DD'))::double precision,s.base)-coalesce(r.reduction,0.0))))
        FROM days d LEFT JOIN reductions r ON r.pool_id=d.pool_id AND r.day=d.day WHERE d.pool_id=s.pool_id),'{}'::jsonb)
    FROM staffing s
$$;
REVOKE ALL ON FUNCTION eppm.pool_effective_capacity(bigint[]) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION eppm.pool_effective_capacity(bigint[]) TO eppm_runtime;
