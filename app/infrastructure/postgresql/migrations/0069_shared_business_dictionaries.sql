-- Consolidate only project roles and event types; keep dictionary-qualified IDs.
SET LOCAL search_path = pg_catalog, eppm;

CREATE TABLE eppm.business_dictionary (
    code text PRIMARY KEY CHECK (code IN ('project_role', 'project_event_type'))
);
INSERT INTO eppm.business_dictionary VALUES ('project_role'), ('project_event_type');
CREATE TABLE eppm.business_dictionary_entry (
    dictionary_code text NOT NULL REFERENCES eppm.business_dictionary(code) ON DELETE RESTRICT,
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    code text NOT NULL,
    name text NOT NULL CHECK (length(trim(name)) > 0),
    system_code text,
    PRIMARY KEY (dictionary_code, id),
    UNIQUE (dictionary_code, code),
    UNIQUE (dictionary_code, system_code),
    CHECK (system_code IS NULL OR dictionary_code = 'project_event_type')
);
CREATE UNIQUE INDEX business_dictionary_name
    ON eppm.business_dictionary_entry(dictionary_code, lower(name));
CREATE TABLE eppm.business_dictionary_translation (
    dictionary_code text NOT NULL,
    entry_id bigint NOT NULL,
    locale text NOT NULL,
    label text NOT NULL CHECK (length(trim(label)) > 0),
    PRIMARY KEY (dictionary_code, entry_id, locale),
    FOREIGN KEY (dictionary_code, entry_id)
        REFERENCES eppm.business_dictionary_entry(dictionary_code, id) ON DELETE CASCADE
);

INSERT INTO eppm.business_dictionary_entry(dictionary_code,id,code,name,system_code)
    SELECT 'project_role',id,'entry_' || id,name,NULL FROM eppm.project_role
    UNION ALL
    SELECT 'project_event_type',id,'entry_' || id,name,system_code FROM eppm.project_event_type;
INSERT INTO eppm.business_dictionary_translation(dictionary_code,entry_id,locale,label)
    SELECT 'project_role',catalog_id,locale,label FROM eppm.project_role_translation
    UNION ALL
    SELECT 'project_event_type',catalog_id,locale,label FROM eppm.project_event_type_translation;

DO $$
BEGIN
    IF EXISTS (
        (SELECT 'project_role'::text,id,name,NULL::text FROM eppm.project_role
         UNION ALL SELECT 'project_event_type',id,name,system_code FROM eppm.project_event_type)
        EXCEPT SELECT dictionary_code,id,name,system_code FROM eppm.business_dictionary_entry
    ) OR EXISTS (
        (SELECT 'project_role'::text,catalog_id,locale,label FROM eppm.project_role_translation
         UNION ALL SELECT 'project_event_type',catalog_id,locale,label FROM eppm.project_event_type_translation)
        EXCEPT SELECT dictionary_code,entry_id,locale,label FROM eppm.business_dictionary_translation
    ) THEN
        RAISE EXCEPTION 'Dictionary migration did not preserve catalog values';
    END IF;
END $$;
SELECT setval(pg_get_serial_sequence('eppm.business_dictionary_entry','id'),
    greatest(coalesce((SELECT max(id) FROM eppm.business_dictionary_entry),0),0) + 1, false);

