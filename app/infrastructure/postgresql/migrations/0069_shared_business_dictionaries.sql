CREATE FUNCTION eppm.guard_dictionary_identity() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, eppm, pg_temp AS $$
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF ROW(NEW.dictionary_code,NEW.id,NEW.code,NEW.system_code)
            IS DISTINCT FROM ROW(OLD.dictionary_code,OLD.id,OLD.code,OLD.system_code) THEN
            RAISE EXCEPTION 'Dictionary identity and classification are immutable' USING ERRCODE='23514';
        END IF;
        RETURN NEW;
    END IF;
    NEW.code := coalesce(NEW.code, 'entry_' || NEW.id);
    IF NEW.dictionary_code = 'project_event_type' AND NEW.name = 'Blocking Point'
        AND NEW.system_code IS NULL THEN
        PERFORM pg_advisory_xact_lock(hashtextextended('eppm:event-type-classification',0));
        IF NOT EXISTS (SELECT 1 FROM eppm.business_dictionary_entry
            WHERE dictionary_code='project_event_type' AND system_code='blocking_point') THEN
            NEW.system_code := 'blocking_point';
        END IF;
    END IF;
    RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION eppm.guard_dictionary_identity() FROM PUBLIC,eppm_runtime;
CREATE TRIGGER dictionary_identity BEFORE INSERT OR UPDATE ON eppm.business_dictionary_entry
    FOR EACH ROW EXECUTE FUNCTION eppm.guard_dictionary_identity();

