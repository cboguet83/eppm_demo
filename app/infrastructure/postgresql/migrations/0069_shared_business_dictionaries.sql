        EXECUTE format('CREATE POLICY dictionary_read ON eppm.%I FOR SELECT TO eppm_runtime
            USING ((SELECT eppm.has_business_read()))',target);
        EXECUTE format('CREATE POLICY dictionary_insert ON eppm.%I FOR INSERT TO eppm_runtime
            WITH CHECK ((SELECT eppm.has_global_permission(''business.manage'')))',target);
        EXECUTE format('CREATE POLICY dictionary_update ON eppm.%I FOR UPDATE TO eppm_runtime
            USING ((SELECT eppm.has_business_read()))
            WITH CHECK ((SELECT eppm.has_global_permission(''business.manage'')))',target);
        EXECUTE format('CREATE POLICY dictionary_delete ON eppm.%I FOR DELETE TO eppm_runtime
            USING ((SELECT eppm.has_business_read()))',target);
        EXECUTE format('CREATE TRIGGER authorize_business BEFORE INSERT OR UPDATE OR DELETE ON eppm.%I
            FOR EACH ROW EXECUTE FUNCTION eppm.guard_business_write(''shared'')',target);
        EXECUTE format('CREATE TRIGGER cache_revision AFTER INSERT OR UPDATE OR DELETE ON eppm.%I
            FOR EACH ROW EXECUTE FUNCTION eppm.invalidate_business_caches(''catalog'')',target);
    END LOOP;
END $$;
